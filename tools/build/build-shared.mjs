#!/usr/bin/env node
/**
 * Bundles the pure list / status logic of the frontend for the adapter.
 *
 *   node tools/build/build-shared.mjs          → writes lib/shared/auraShared.js
 *   node tools/build/build-shared.mjs --check  → fails when the file is out of date
 *
 * The output is committed: the adapter ships lib/, not src-vis/, and has no build
 * step at install time. `npm test` runs the check, so a change to listFilter.ts &
 * co. without a rebuild is caught before it reaches a release.
 */
import { build } from 'esbuild';
import { readFileSync, writeFileSync, mkdirSync, existsSync } from 'node:fs';
import { dirname, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';

const ROOT = resolve(dirname(fileURLToPath(import.meta.url)), '../..');
const ENTRY = resolve(ROOT, 'tools/build/shared-entry.ts');
const OUT = resolve(ROOT, 'lib/shared/auraShared.js');
const check = process.argv.includes('--check');

const HEADER = `/* eslint-disable */
// GENERATED by tools/build/build-shared.mjs from tools/build/shared-entry.ts — do not edit.
// Rebuild with \`npm run shared\` after changing the bundled src-vis/utils modules.
`;

// Only these may end up in the bundle. A store, a hook or React reaching in through a
// re-export would turn the adapter into a frontend — fail loudly instead.
const ALLOWED = /[\\/]src-vis[\\/](utils|types)[\\/]|[\\/]tools[\\/]build[\\/]shared-entry\.ts$/;

const result = await build({
    entryPoints: [ENTRY],
    bundle: true,
    platform: 'node',
    format: 'cjs',
    target: 'node18',
    write: false,
    metafile: true,
    legalComments: 'none',
    logLevel: 'silent',
});

const bad = Object.keys(result.metafile.inputs).filter((p) => !ALLOWED.test(resolve(ROOT, p)));
if (bad.length) {
    console.error(`[shared] not allowed in the adapter bundle:\n  ${bad.join('\n  ')}`);
    process.exit(1);
}

// Paths in esbuild's module comments are relative to the cwd; normalise the
// separators so a Windows and a Linux build produce the same file.
const code =
    HEADER +
    result.outputFiles[0].text
        .replace(/\r\n/g, '\n')
        .replace(/\/\/ (src-vis|tools)\\[^\n]*/g, (m) => m.replace(/\\/g, '/'));

if (check) {
    const current = existsSync(OUT) ? readFileSync(OUT, 'utf8').replace(/\r\n/g, '\n') : '';
    if (current !== code) {
        console.error('[shared] lib/shared/auraShared.js is out of date — run `npm run shared` and commit it.');
        process.exit(1);
    }
    console.log('[shared] lib/shared/auraShared.js up to date');
} else {
    mkdirSync(dirname(OUT), { recursive: true });
    writeFileSync(OUT, code);
    console.log(`[shared] wrote lib/shared/auraShared.js (${Object.keys(result.metafile.inputs).length} modules)`);
}
