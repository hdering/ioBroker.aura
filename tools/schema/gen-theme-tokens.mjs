#!/usr/bin/env node
/**
 * Publishes the theme palette as JSON, so a model can use the dashboard's own
 * colours instead of inventing hex values.
 *
 *   node tools/schema/gen-theme-tokens.mjs          write public/ai/aura-theme-tokens.json
 *   node tools/schema/gen-theme-tokens.mjs --check  fail if the file is out of date
 *
 * Reported from use: the widget schema mentions `var(--accent-green)` and
 * `var(--text-secondary)` in its descriptions, but nothing anywhere listed the
 * tokens — so a generated dashboard came back full of #f59e0b and #94a3b8, which
 * hold up in one theme and clash in the next. The tokens are the whole point of
 * the theme system: they follow light/dark and every user preset.
 *
 * Values come from the real module (bundled and executed, like the widget
 * registry), the one-line explanations from the interface comments next to them.
 * Nothing here is hand-copied, so the palette cannot drift from the app.
 */

import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath, pathToFileURL } from 'node:url';
import esbuild from 'esbuild';

import { SourceIndex } from './ts-source-index.mjs';

const HERE = path.dirname(fileURLToPath(import.meta.url));
const ROOT = path.resolve(HERE, '../..');
const SRC = path.join(ROOT, 'src-vis');
const OUT_FILE = path.join(ROOT, 'public/ai/aura-theme-tokens.json');
const CACHE_DIR = path.join(ROOT, 'node_modules/.cache');

async function loadThemes() {
    fs.mkdirSync(CACHE_DIR, { recursive: true });
    const entry = path.join(CACHE_DIR, 'aura-theme-entry.ts');
    fs.writeFileSync(
        entry,
        `export { THEMES, ELEMENT_VAR_FALLBACKS, DEFAULT_THEME_ID } from ${JSON.stringify(
            path.join(SRC, 'themes/index').replace(/\\/g, '/'),
        )};\n`,
    );
    const outfile = path.join(CACHE_DIR, 'aura-theme-tokens.mjs');
    await esbuild.build({
        entryPoints: [entry],
        outfile,
        bundle: true,
        format: 'esm',
        platform: 'node',
        logLevel: 'silent',
    });
    return import(`${pathToFileURL(outfile).href}?t=${Date.now()}`);
}

/**
 * Group headings and trailing notes from an interface of quoted CSS-var keys.
 *
 * The shared field reader skips these interfaces entirely — their keys are
 * quoted ('--app-bg': string) — and what is worth having here is not a type
 * anyway but the `// App` / `// Akzente` headings that group the palette and the
 * odd trailing note ("on" track).
 *
 * @param name the interface name
 * @returns {Record<string, {group?: string, description?: string}>}
 */
function varComments(name) {
    const body = index.interfaceBody(name);
    const out = {};
    let group;
    for (const line of ((body && body.body) || '').split('\n')) {
        const heading = line.match(/^\s*\/\/\s*(.+?)\s*$/);
        if (heading) {
            group = heading[1];
            continue;
        }
        const field = line.match(/^\s*'([^']+)'\s*\??\s*:\s*[^;]+;\s*(?:\/\/\s*(.*))?$/);
        if (field) {
            out[field[1]] = {
                ...(group ? { group } : {}),
                ...(field[2] ? { description: field[2].trim() } : {}),
            };
        }
    }
    return out;
}

const { THEMES, ELEMENT_VAR_FALLBACKS, DEFAULT_THEME_ID } = await loadThemes();
const index = new SourceIndex(SRC);
const baseDocs = varComments('ThemeVars');
const elementDocs = varComments('ElementVars');

const baseTokens = Object.keys(THEMES[0].vars).map((name) => ({ name, ...(baseDocs[name] || {}) }));

const elementTokens = Object.entries(ELEMENT_VAR_FALLBACKS).map(([name, fallback]) => ({
    name,
    // What it falls back to when unset — a widget writes
    // `var(--switch-bg, var(--accent-green))`, so the base token is the honest
    // answer to "what colour is this actually".
    inherits: fallback,
    ...(elementDocs[name] || {}),
}));

const { version } = JSON.parse(fs.readFileSync(path.join(ROOT, 'package.json'), 'utf8'));

const payload = {
    $meta: {
        auraVersion: version,
        source: 'src-vis/themes/index.ts — generated by tools/schema/gen-theme-tokens.mjs, do not edit',
        usage: [
            'Colours in a widget belong in a var(): "var(--accent-green)", not "#22c55e".',
            'A hard-coded hex survives one theme and clashes in the next — the user switches light/dark.',
            'The element tokens are optional overrides; unset they inherit the base token under "inherits".',
        ],
    },
    defaultThemeId: DEFAULT_THEME_ID,
    baseTokens,
    elementTokens,
    themes: THEMES.map((t) => ({ id: t.id, name: t.name, dark: t.dark, vars: t.vars })),
};

const json = `${JSON.stringify(payload, null, 2)}\n`;
const current = fs.existsSync(OUT_FILE) ? fs.readFileSync(OUT_FILE, 'utf8') : '';

if (process.argv.includes('--check')) {
    if (current !== json) {
        console.error('public/ai/aura-theme-tokens.json is out of date — run: npm run theme-tokens');
        process.exit(1);
    }
    console.log(`public/ai/aura-theme-tokens.json: up to date (${payload.themes.length} themes)`);
} else {
    fs.mkdirSync(path.dirname(OUT_FILE), { recursive: true });
    fs.writeFileSync(OUT_FILE, json);
    console.log(
        `public/ai/aura-theme-tokens.json: ${payload.themes.length} Themes, ` +
            `${baseTokens.length} Basis-Token, ${elementTokens.length} Element-Token`,
    );
}
